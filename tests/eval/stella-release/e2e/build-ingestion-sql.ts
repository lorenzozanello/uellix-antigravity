// tests/eval/stella-release/e2e/build-ingestion-sql.ts
// RELEASE line — Train 4. Turns the two REAL fixture documents into:
//
//   1. seed SQL       — organizations/users/organization_members/projects/
//                        evidence_items, applied as uellix_owner.
//   2. ingestion SQL   — register_document_version -> insert_evidence_chunks
//                        -> finalize_document_ingestion, applied as
//                        uellix_app with a real request.jwt.claims GUC set
//                        (the same mechanism db/identity-context.ts's
//                        withDatabaseIdentityContext uses in production —
//                        see current_user_org_ids()/auth.uid()).
//   3. a manifest       — everything the journey orchestrator needs to
//                        assert against afterward (chunk ids, hashes,
//                        expected counts), so it never has to re-derive or
//                        assume a value this module already computed for
//                        real.
//
// THE RESULT IS NOT ASSUMED. `ingestFixtureDocuments` calls the actual
// lib/grounding/ingest pipeline (extract -> normalize -> version -> chunk)
// over the real .txt bytes on disk and THROWS if either document does not
// come back `status: 'ingested'` — there is no fallback to a hand-built
// chunk list. Every id, hash and offset the emitted SQL carries is read off
// that real output.
//
// No database connection here. No docker. No provider. Pure computation plus
// two file reads.

import { readFileSync } from 'node:fs'
import path from 'node:path'
import {
  hashContent,
  INJECTION_SCANNER_VERSION,
  type ContentHash,
  type GroundingChunk,
  type GroundingScope,
  type SourceDocument,
} from '@/lib/grounding/contracts'
import { ingestDocument, type IngestionIngested } from '@/lib/grounding/ingest'
import {
  E2E_CONTRADICTING_PLANTING_COUNTS,
  E2E_DECOY_PROJECT_ID,
  E2E_ORGANIZATION_ID,
  E2E_PROJECT_ID,
  E2E_QUERY_WITH_CONTRADICTION,
  E2E_QUERY_WITH_NO_MATCH,
  E2E_SOURCE_DOCUMENTS,
  E2E_USER_ID,
  e2eFixtureDocsDir,
  type E2eSourceDocumentFixture,
} from '../fixtures/e2e/fixture-metadata'

export interface IngestedFixtureDocument {
  readonly source: E2eSourceDocumentFixture
  readonly outcome: IngestionIngested
}

/** Postgres single-quoted string literal, doubling embedded quotes. Every
 *  value passed through this in this module is our own derived id/hash/text
 *  — nothing here is untrusted user input, but the escaping is applied
 *  unconditionally rather than "trusted because short". */
function sqlString(value: string): string {
  return `'${value.replace(/'/g, "''")}'`
}

function sqlJsonb(value: unknown): string {
  return `${sqlString(JSON.stringify(value))}::jsonb`
}

/**
 * Runs the real ingestion pipeline over the two fixture documents. Fail
 * closed: a document that skips or is rejected stops the whole build rather
 * than silently producing a manifest for a document that was never actually
 * indexed — the Fase 3 "no sustituya faltantes por fixtures" instruction
 * applies to this module's own output too.
 */
export function ingestFixtureDocuments(root: string = process.cwd()): readonly IngestedFixtureDocument[] {
  const docsDir = e2eFixtureDocsDir(root)
  const scope: GroundingScope = { organizationId: E2E_ORGANIZATION_ID, projectId: E2E_PROJECT_ID }

  return E2E_SOURCE_DOCUMENTS.map((source) => {
    const filePath = path.join(docsDir, source.filename)
    const bytes = readFileSync(filePath)

    const sourceDocument: SourceDocument = {
      evidenceId: source.evidenceId,
      scope,
      kind: 'file',
      label: source.filename,
      mimeType: source.mimeType,
      byteSize: bytes.length,
    }

    const outcome = ingestDocument(sourceDocument, bytes)
    if (outcome.status !== 'ingested') {
      throw new Error(
        `build-ingestion-sql: fixture document ${source.filename} did not ingest (status=${outcome.status}${
          'reason' in outcome ? `, reason=${outcome.reason}` : ''
        }) — the E2E journey requires a REAL ingested document, not a fallback`,
      )
    }
    if (outcome.chunks.length === 0) {
      throw new Error(`build-ingestion-sql: fixture document ${source.filename} ingested with zero chunks`)
    }

    return { source, outcome }
  })
}

/**
 * organizations -> users -> organization_members -> projects ->
 * evidence_items. Written to be applied as `uellix_owner` (mirrors
 * scripts/grounding-dry-run.sh section 6-ter), NOT through RLS — seeding
 * fixture rows is not the boundary this journey exists to test; the
 * grounding functions' own scope checks are.
 */
export function buildSeedSql(ingested: readonly IngestedFixtureDocument[]): string {
  const lines: string[] = [
    '-- Generated by tests/eval/stella-release/e2e/build-ingestion-sql.ts — DO NOT EDIT BY HAND.',
    'SET ROLE uellix_owner;',
    '',
    `INSERT INTO public.organizations (id, name, slug) VALUES`,
    `  (${sqlString(E2E_ORGANIZATION_ID)}, 'Stella Release E2E Org', 'stella-release-e2e-org');`,
    '',
    `INSERT INTO public.users (id, email) VALUES`,
    `  (${sqlString(E2E_USER_ID)}, 'stella-release-e2e@example.invalid');`,
    '',
    `INSERT INTO public.organization_members (organization_id, user_id, role, status) VALUES`,
    `  (${sqlString(E2E_ORGANIZATION_ID)}, ${sqlString(E2E_USER_ID)}, 'organization_admin', 'active');`,
    '',
    `INSERT INTO public.projects (id, organization_id, name, created_by) VALUES`,
    `  (${sqlString(E2E_PROJECT_ID)}, ${sqlString(E2E_ORGANIZATION_ID)}, 'Rio Verde Watershed Restoration', ${sqlString(E2E_USER_ID)}),`,
    `  (${sqlString(E2E_DECOY_PROJECT_ID)}, ${sqlString(E2E_ORGANIZATION_ID)}, 'Decoy Project (isolation control)', ${sqlString(E2E_USER_ID)});`,
    '',
    'INSERT INTO public.evidence_items (id, project_id, organization_id, type, title, created_by) VALUES',
  ]

  const evidenceRows = ingested.map(({ source }) =>
    `  (${sqlString(source.evidenceId)}, ${sqlString(E2E_PROJECT_ID)}, ${sqlString(E2E_ORGANIZATION_ID)}, 'file', ${sqlString(source.title)}, ${sqlString(E2E_USER_ID)})`,
  )
  lines.push(evidenceRows.join(',\n') + ';')
  lines.push('', 'RESET ROLE;')

  return lines.join('\n') + '\n'
}

function chunkPayload(chunk: GroundingChunk): Record<string, unknown> {
  return {
    chunk_id: chunk.chunkId,
    chunk_index: chunk.chunkIndex,
    content: chunk.text,
    content_hash: chunk.contentHash,
    char_start: chunk.location.span.start,
    char_end: chunk.location.span.end,
    page: chunk.location.page,
    section_index: chunk.location.sectionIndex,
    signals: chunk.signals,
    canonical_chunk_id: null,
    embedding_provider_id: null,
    injection_scanner_version: chunk.provenance.injectionScannerVersion,
  }
}

/**
 * register_document_version -> insert_evidence_chunks ->
 * finalize_document_ingestion for every ingested document, chained through
 * psql `\gset` (the uuid `register_document_version` returns is not known
 * until the call runs, and `insert_evidence_chunks` needs it) — applied as
 * `uellix_app` under a real `request.jwt.claims` GUC, exactly the identity
 * db/identity-context.ts's withDatabaseIdentityContext establishes for a
 * production request. This is the step that makes the run a real exercise of
 * `current_user_org_ids()` returning a NON-empty set (U0102's anonymous path,
 * already covered by scripts/grounding-dry-run.sh 6-bis, is not this train's
 * job to re-prove).
 */
export function buildIngestSql(ingested: readonly IngestedFixtureDocument[]): string {
  const claims = JSON.stringify({ sub: E2E_USER_ID, role: 'authenticated' })

  const lines: string[] = [
    '-- Generated by tests/eval/stella-release/e2e/build-ingestion-sql.ts — DO NOT EDIT BY HAND.',
    'RESET ROLE;',
    'SET ROLE uellix_app;',
    `SELECT set_config('request.jwt.claims', ${sqlString(claims)}, true);`,
    '',
  ]

  for (const { source, outcome } of ingested) {
    const { version } = outcome.document
    const { chunks } = outcome
    // DocumentVersion carries no chunkerVersion of its own (see
    // lib/grounding/contracts/documents.ts) — it lives on each chunk's
    // ProvenanceRecord instead. Every chunk of one document shares it, so
    // reading it off the first chunk is exact, not an approximation.
    const chunkerVersion = chunks[0].provenance.chunkerVersion
    const varName = `docver_${source.evidenceId.slice(-2)}`
    lines.push(
      `-- ${source.filename} (evidence ${source.evidenceId})`,
      `SELECT uellix_grounding.register_document_version(`,
      `  ${sqlString(source.evidenceId)}::uuid,`,
      `  ${sqlString(version.versionId)}::char(64),`,
      `  ${sqlString(version.rawContentHash)}::char(64),`,
      `  ${sqlString(version.normalizedContentHash)}::char(64),`,
      `  ${sqlString(version.normalizationVersion)}::varchar(32),`,
      `  ${sqlString(version.extractorVersion)}::varchar(32),`,
      `  ${sqlString(chunkerVersion)}::varchar(32),`,
      `  ${sqlString(source.mimeType)}::varchar(255)`,
      `) AS ${varName} \\gset`,
      '',
      `SELECT uellix_grounding.insert_evidence_chunks(:'${varName}'::uuid, ${sqlJsonb(chunks.map(chunkPayload))}) AS ${varName}_inserted \\gset`,
      `SELECT uellix_grounding.finalize_document_ingestion(:'${varName}'::uuid, ${chunks.length});`,
      '',
    )
  }

  lines.push('RESET ROLE;')
  return lines.join('\n') + '\n'
}

export interface E2eJourneyManifest {
  readonly organizationId: string
  readonly userId: string
  readonly projectId: string
  readonly decoyProjectId: string
  readonly queryWithContradiction: string
  readonly queryWithNoMatch: string
  readonly documents: readonly {
    readonly evidenceId: string
    readonly title: string
    readonly mimeType: string
    readonly versionId: ContentHash
    readonly rawContentHash: ContentHash
    readonly chunkIds: readonly ContentHash[]
    readonly expectedChunkCount: number
    readonly plantingCountClaimed: number
  }[]
}

export function buildManifest(ingested: readonly IngestedFixtureDocument[]): E2eJourneyManifest {
  return {
    organizationId: E2E_ORGANIZATION_ID,
    userId: E2E_USER_ID,
    projectId: E2E_PROJECT_ID,
    decoyProjectId: E2E_DECOY_PROJECT_ID,
    queryWithContradiction: E2E_QUERY_WITH_CONTRADICTION,
    queryWithNoMatch: E2E_QUERY_WITH_NO_MATCH,
    documents: ingested.map(({ source, outcome }) => ({
      evidenceId: source.evidenceId,
      title: source.title,
      mimeType: source.mimeType,
      versionId: outcome.document.version.versionId,
      rawContentHash: outcome.document.version.rawContentHash,
      chunkIds: outcome.chunks.map((c) => c.chunkId),
      expectedChunkCount: outcome.chunks.length,
      plantingCountClaimed: E2E_CONTRADICTING_PLANTING_COUNTS[source.evidenceId],
    })),
  }
}

